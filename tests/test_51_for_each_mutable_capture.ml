// ============================================================
// Test 51: for_each ラムダ内ミュータブルキャプチャ（#83）
//   A. 基本ミュータブルキャプチャ（sum の累積）                              [C0]
//   B. 複数変数のミュータブルキャプチャ（total / count）                     [C1]
//   C. 読み取り専用キャプチャとミュータブルキャプチャの混在（base / acc）     [C1]
//
// カバレッジ観点:
//   C0: ミュータブルキャプチャが正しくポインタ経由で渡されること
//   C1: 複数変数・混在ケースでもコンパイル・実行が正常終了すること
// ============================================================

fn main() -> i32 {
    println("=== 51: for_each mutable capture ===");

    // ----------------------------------------------------------
    // A. 基本ミュータブルキャプチャ
    // ----------------------------------------------------------
    println("--- A: basic mutable capture ---");
    let nums: i32[] = [1, 2, 3, 4, 5];
    let sum: i32 = 0;
    nums.for_each((x: i32) => { sum = sum + x; });
    println("A1: sum={}", sum);    // A1: sum=15

    // ----------------------------------------------------------
    // B. 複数変数のミュータブルキャプチャ
    // ----------------------------------------------------------
    println("--- B: multiple mutable captures ---");
    let vals: i32[] = [10, 20, 30];
    let total: i32 = 0;
    let count: i32 = 0;
    vals.for_each((x: i32) => {
        total = total + x;
        count = count + 1;
    });
    println("B1: total={}", total);  // B1: total=60
    println("B2: count={}", count);  // B2: count=3

    // ----------------------------------------------------------
    // C. 読み取り専用キャプチャとミュータブルキャプチャの混在
    // ----------------------------------------------------------
    println("--- C: mixed captures ---");
    let base: i32 = 100;
    let acc: i32 = 0;
    let items: i32[] = [1, 2, 3];
    items.for_each((x: i32) => { acc = acc + x + base; });
    println("C1: acc={}", acc);  // C1: acc=306

    println("=== OK ===");
    return 0;
}
